    !--------------------------------------------------------------------------
    ! Date picker / Time picker menu commands
    !--------------------------------------------------------------------------
    subroutine on_ask_date(fun, data, evt) bind(C)
        type(c_ptr), value :: fun, data, evt
        type(wxdatetime_t) :: dt_in, dt, today
        integer :: style
        logical :: accepted
        integer(c_int) :: res

        if (.not. c_associated(evt)) return

        dt_in = wx_date_time_create()
        call wx_calendar_ctrl_base_get_date(g_cal, dt_in%ptr)

        style = wxDP_DEFAULT()
        if (menu_checked(ID_DATE_SHOWCENTURY)) style = ior(style, wxDP_SHOWCENTURY())
        if (menu_checked(ID_DATE_DROPDOWN)) style = ior(style, wxDP_DROPDOWN())
        if (menu_checked(ID_DATE_ALLOWNONE)) then
            style = ior(style, wxDP_ALLOWNONE())
            if (menu_checked(ID_DATE_STARTNONE)) then
                call wx_date_time_delete(dt_in)
                dt_in = wx_date_time_create()   ! wxDefaultDateTime
            end if
        end if

        dt%ptr = c_null_ptr
        dt%owned = .false.
        call run_date_dialog(dt_in, style, accepted, dt)

        if (accepted) then
            if (wx_date_time_is_valid(dt)) then
                today = wx_date_time_create()
                call wx_date_time_today(today)
                if (wx_date_time_get_day(dt, wxDateTime_Local()) == &
                        wx_date_time_get_day(today, wxDateTime_Local()) .and. &
                    wx_date_time_get_month(dt, wxDateTime_Local()) == &
                        wx_date_time_get_month(today, wxDateTime_Local())) then
                    res = message_box("Happy birthday!", "Calendar Sample")
                end if
                call wx_date_time_delete(today)

                call set_cal_date(dt)
                call log_status("Changed the date to your input")
            else
                call log_status("No date entered")
            end if
            call wx_date_time_delete(dt)
        end if

        call wx_date_time_delete(dt_in)
    end subroutine on_ask_date

    subroutine on_ask_time(fun, data, evt) bind(C)
        type(c_ptr), value :: fun, data, evt
        logical :: accepted
        type(wxdatetime_t) :: dt
        if (.not. c_associated(evt)) return

        dt%ptr = c_null_ptr
        dt%owned = .false.
        call run_time_dialog(accepted, dt)
        if (accepted) then
            call log_message("You entered " // iso_time(dt))
            call wx_date_time_delete(dt)
        end if
    end subroutine on_ask_time

    !--------------------------------------------------------------------------
    ! MyDateDialog -- "Calendar: Choose a date"
    !--------------------------------------------------------------------------
    subroutine run_date_dialog(dt_in, style, accepted, dt_out)
        type(wxdatetime_t), intent(in) :: dt_in
        integer, intent(in) :: style
        logical, intent(out) :: accepted
        type(wxdatetime_t), intent(out) :: dt_out

        type(wxdialog_t) :: dlg
        type(wxdatepickerctrl_t) :: picker
        type(wxStaticText_t) :: enter_label, iso_label
        type(wxFlexGridSizer_t) :: grid
        type(wxBoxSizer_t) :: topsizer
        type(wxstddialogbuttonsizer_t) :: btn_sizer
        type(wxdatetime_t) :: jan1, invalid
        integer(c_int) :: res
        integer :: iflag
        logical :: ok

        accepted = .false.
        dt_out%ptr = c_null_ptr
        dt_out%owned = .false.
        iflag = ior(wxALIGN_CENTER(), wxALL())

        dlg = wx_dialog_create(g_frame, wxID_ANY(), &
            "Calendar: Choose a date", -1_c_int, -1_c_int, -1_c_int, -1_c_int, &
            wxDEFAULT_DIALOG_STYLE())
        if (.not. dlg%is_valid()) return

        ! wxDatePickerCtrl(this, wxID_ANY, dt, wxDefaultPosition,
        !                  wxDefaultSize, dtpStyle)
        picker = wx_date_picker_ctrl_create(dlg, wxID_ANY(), dt_in, &
            -1_c_int, -1_c_int, -1_c_int, -1_c_int, int(style, c_long))

        ! SetRange(wxDateTime(1, wxDateTime::Jan, 1900), wxDefaultDateTime)
        jan1 = make_datetime(1, 0, 1900, 0, 0, 0)
        invalid = wx_date_time_create()
        call wx_date_picker_ctrl_set_range(picker, jan1, invalid)
        call wx_date_time_delete(jan1)
        call wx_date_time_delete(invalid)

        g_date_text = wx_static_text_create(dlg, wxID_ANY(), iso_date(dt_in), &
            -1_c_int, -1_c_int, -1_c_int, -1_c_int, 0_c_int)
        enter_label = wx_static_text_create(dlg, wxID_ANY(), "Enter &date:", &
            -1_c_int, -1_c_int, -1_c_int, -1_c_int, 0_c_int)
        iso_label = wx_static_text_create(dlg, wxID_ANY(), &
            "Date in ISO format:", -1_c_int, -1_c_int, -1_c_int, -1_c_int, 0_c_int)

        grid = wx_flex_grid_sizer_create(0_c_int, 2_c_int, 0_c_int, 0_c_int)
        call wx_sizer_add_window(grid, enter_label, 0_c_int, iflag, &
            g_border1, c_null_ptr)
        call wx_sizer_add_window(grid, picker, 0_c_int, iflag, &
            g_border1, c_null_ptr)
        call wx_sizer_add_window(grid, iso_label, 0_c_int, iflag, &
            g_border1, c_null_ptr)
        call wx_sizer_add_window(grid, g_date_text, 0_c_int, iflag, &
            g_border1, c_null_ptr)

        topsizer = wx_box_sizer_create(wxVERTICAL())
        call wx_sizer_add_sizer(topsizer, grid, 0_c_int, iflag, &
            g_border1, c_null_ptr)

        btn_sizer = wx_dialog_create_std_dialog_button_sizer(dlg, &
            int(ior(wxOK(), wxCANCEL()), c_long))
        call wx_sizer_add_sizer(topsizer, btn_sizer, 0_c_int, iflag, &
            g_border1, c_null_ptr)

        call wx_window_set_sizer_and_fit(dlg, topsizer, .true.)

        call wx_connect(dlg, wxEVT_DATE_CHANGED(), on_date_change)

        res = wx_dialog_show_modal(dlg)

        if (res == wxID_OK()) then
            dt_out = wx_date_time_create()
            call wx_date_picker_ctrl_get_value(picker, dt_out)
            accepted = .true.
        end if

        ok = wx_window_destroy(dlg)
        g_date_text%ptr = c_null_ptr
        g_date_text%owned = .false.
    end subroutine run_date_dialog

    subroutine on_date_change(fun, data, evt) bind(C)
