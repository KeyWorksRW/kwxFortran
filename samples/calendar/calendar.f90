module calendar_ops
    use, intrinsic :: iso_c_binding
    use kwx_types
    use kwxffi, only: wxCAL_BORDER_ROUND, wxCAL_BORDER_SQUARE, &
        wxCAL_BORDER_NONE, wxCAL_SEQUENTIAL_MONTH_SELECTION, &
        wxCAL_SHOW_WEEK_NUMBERS, wxCAL_HITTEST_HEADER, wxCAL_HITTEST_DAY, &
        wxCAL_HITTEST_INCMONTH, wxCAL_HITTEST_DECMONTH, &
        wxCAL_HITTEST_SURROUNDING_WEEK, wxRED, wxGREEN, wxBLUE, wxLIGHT_GREY, &
        wxEVT_RIGHT_DOWN, wxEXPAND, wxALIGN_CENTER
    use wx_calendar_ctrl, only: wx_calendar_ctrl_create
    use wx_generic_calendar_ctrl, only: wx_generic_calendar_ctrl_create
    use wx_calendar_ctrl_base, only: wx_calendar_ctrl_base_get_date, &
        wx_calendar_ctrl_base_set_date, wx_calendar_ctrl_base_mark, &
        wx_calendar_ctrl_base_set_attr, wx_calendar_ctrl_base_reset_attr, &
        wx_calendar_ctrl_base_hit_test, wx_calendar_ctrl_base_set_date_range, &
        wx_calendar_ctrl_base_get_date_range
    use wx_calendar_date_attr, only: wx_calendar_date_attr_create, &
        wx_calendar_date_attr_create_border
    use wx_date_span, only: wx_date_span_create_from_months, wx_date_span_delete
    use wx_date_time, only: wx_date_time_create, wx_date_time_delete, &
        wx_date_time_today, wx_date_time_subtract_date, wx_date_time_add_date, &
        wx_date_time_get_year
