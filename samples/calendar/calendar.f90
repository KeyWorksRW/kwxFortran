! calendar.f90 - wxCalendarCtrl sample (kwxFortran port)
!
! Fortran port of wxWidgets sample src/calendar/calendar.cpp, written against
! the per-class wrappers generated by kwxgen (wx_calendar_ctrl,
! wx_calendar_ctrl_base, wx_generic_calendar_ctrl, wx_date_time, ...).
!
! Layout of the original C++ sample:
!   * MyFrame with File / Calendar / Date picker / Time picker menus.
!   * A horizontal splitter holding MyPanel (static text + wxCalendarCtrl)
!     above a read-only wxTextCtrl which is installed as the wxLog target.
!   * Menu commands toggle calendar styles, attributes, date range and the
!     native/generic calendar implementation, and open the date/time dialogs.
!
! Platform conditionals of the C++ source:
!   * wxHAS_NATIVE_CALENDARCTRL: enabled on MSW; the "Use generic version"
!     menu item and the wxGenericCalendarCtrl branch are ported.
!   * wxUSE_DATEPICKCTRL_GENERIC / wxUSE_TIMEPICKCTRL_GENERIC: disabled on
!     MSW; the generic picker branch and its menu items are not compiled by
!     the original sample on this platform and are therefore not ported.
!   * __WXGTK__ extra EVT_UPDATE_UI entries: MSW does not take that branch.
!
! Run the executable with the current directory set to this folder.

