    use wx_sizer, only: wx_sizer_replace_window, wx_sizer_layout, &
        wx_sizer_get_item_window
    use wx_sizer_item, only: wx_sizer_item_set_proportion, wx_sizer_item_set_flag
    use wx_window, only: wx_window_get_window_style, wx_window_set_window_style, &
        wx_window_refresh, wx_window_destroy
    use wx_mouse_event, only: wx_mouse_event_get_x, wx_mouse_event_get_y
    use calendar_globals
    use calendar_util
    implicit none
    private

    public :: create_calendar, recreate_calendar, toggle_cal_style
    public :: set_cal_date, highlight_special, limit_date_range
    public :: toggle_resizable

contains

    !--------------------------------------------------------------------------
    ! MyPanel::DoCreateCalendar()
    !--------------------------------------------------------------------------
    function create_calendar(date, style) result(cal)
        type(wxdatetime_t), intent(in) :: date
        integer, intent(in) :: style
        type(wxCalendarCtrlBase_t) :: cal
        type(wxCalendarCtrl_t) :: native
        type(wxGenericCalendarCtrl_t) :: generic

        cal%ptr = c_null_ptr
        cal%owned = .false.

        if (g_using_generic) then
            generic = wx_generic_calendar_ctrl_create(g_panel, &
                int(ID_CALCTRL, c_int), date, -1_c_int, -1_c_int, &
                -1_c_int, -1_c_int, int(style, c_int))
            cal%ptr = generic%ptr
        else
            native = wx_calendar_ctrl_create(g_panel, int(ID_CALCTRL, c_int), &
                date, -1_c_int, -1_c_int, -1_c_int, -1_c_int, int(style, c_int))
            cal%ptr = native%ptr
        end if

        ! calendar->Bind(wxEVT_RIGHT_DOWN, &MyFrame::OnCalRClick, frame);
        if (cal%is_valid()) call wx_bind(cal, wxEVT_RIGHT_DOWN(), on_cal_rclick)
    end function create_calendar

    !--------------------------------------------------------------------------
    ! MyPanel::RecreateCalendar()
    !--------------------------------------------------------------------------
    subroutine recreate_calendar(style)
        integer, intent(in) :: style
        type(wxCalendarCtrlBase_t) :: cal, old
        type(wxdatetime_t) :: dt
        logical :: ok

        dt = wx_date_time_create()
        call wx_calendar_ctrl_base_get_date(g_cal, dt%ptr)

        cal = create_calendar(dt, style)

        ok = wx_sizer_replace_window(g_sizer, g_cal, cal, .false.)
        old = g_cal
        g_cal = cal
        ok = wx_window_destroy(old)

        call wx_sizer_layout(g_sizer)
        call wx_date_time_delete(dt)
    end subroutine recreate_calendar

    !--------------------------------------------------------------------------
    ! MyPanel::ToggleCalStyle()
    !--------------------------------------------------------------------------
    subroutine toggle_cal_style(on, flag)
        logical, intent(in) :: on
        integer, intent(in) :: flag
        integer(c_long) :: style

        style = wx_window_get_window_style(g_cal)
        if (on) then
            style = ior(style, int(flag, c_long))
        else
            style = iand(style, not(int(flag, c_long)))
        end if

        if (flag == wxCAL_SEQUENTIAL_MONTH_SELECTION() .or. &
                flag == wxCAL_SHOW_WEEK_NUMBERS()) then
            ! changing these styles requires recreating the control
            call recreate_calendar(int(style, c_int))
        else
            call wx_window_set_window_style(g_cal, style)
            call wx_window_refresh(g_cal, .true.)
        end if
    end subroutine toggle_cal_style

    !--------------------------------------------------------------------------
    ! MyPanel::SetDate()
    !--------------------------------------------------------------------------
    subroutine set_cal_date(dt)
        type(wxdatetime_t), intent(in) :: dt
        call wx_calendar_ctrl_base_set_date(g_cal, dt%ptr)
    end subroutine set_cal_date

    !--------------------------------------------------------------------------
    ! MyPanel::HighlightSpecial()
    !--------------------------------------------------------------------------
    subroutine highlight_special(on)
        logical, intent(in) :: on
        type(wxCalendarDateAttr_t) :: attr

        if (on) then
            ! new wxCalendarDateAttr(wxCAL_BORDER_ROUND, *wxRED)
            attr = wx_calendar_date_attr_create_border(wxCAL_BORDER_ROUND(), &
                wxcolour_from_ptr(wxRED(), .false.))
            if (attr%is_valid()) &
                call wx_calendar_ctrl_base_set_attr(g_cal, 17_c_int, attr%ptr)

            ! new wxCalendarDateAttr(wxCAL_BORDER_SQUARE, *wxGREEN)
            attr = wx_calendar_date_attr_create_border(wxCAL_BORDER_SQUARE(), &
                wxcolour_from_ptr(wxGREEN(), .false.))
            if (attr%is_valid()) &
                call wx_calendar_ctrl_base_set_attr(g_cal, 29_c_int, attr%ptr)

            ! new wxCalendarDateAttr(*wxBLUE, *wxLIGHT_GREY)
            attr = wx_calendar_date_attr_create(wxBLUE(), wxLIGHT_GREY(), &
                c_null_ptr, c_null_ptr, wxCAL_BORDER_NONE())
            if (attr%is_valid()) &
                call wx_calendar_ctrl_base_set_attr(g_cal, 13_c_int, attr%ptr)
        else
            call wx_calendar_ctrl_base_reset_attr(g_cal, 17_c_int)
            call wx_calendar_ctrl_base_reset_attr(g_cal, 29_c_int)
            call wx_calendar_ctrl_base_reset_attr(g_cal, 13_c_int)
        end if

        call wx_window_refresh(g_cal, .true.)
    end subroutine highlight_special

    !--------------------------------------------------------------------------
    ! MyPanel::LimitDateRange()
    !--------------------------------------------------------------------------
    subroutine limit_date_range(on)
        logical, intent(in) :: on
        type(wxdatespan_t) :: diff
        type(wxdatetime_t) :: today, lo, hi, first_valid, last_valid

        if (on) then
            diff = wx_date_span_create_from_months(3_c_int)
            today = wx_date_time_create()
            call wx_date_time_today(today)

            lo = wx_date_time_create()
            hi = wx_date_time_create()
            call wx_date_time_subtract_date(today, diff%ptr, lo)
            call wx_date_time_add_date(today, diff%ptr, hi)

            if (wx_calendar_ctrl_base_set_date_range(g_cal, lo%ptr, hi%ptr)) then
                call log_status("Date range limited to 3 months around today.")
                first_valid = wx_date_time_create()
                last_valid = wx_date_time_create()
                if (wx_calendar_ctrl_base_get_date_range(g_cal, &
                        first_valid%ptr, last_valid%ptr)) then
                    call log_message("First valid date: " // &
                        iso_date(first_valid) // ", last valid date: " // &
                        iso_date(last_valid))
                else
                    call log_warning("Failed to get back the valid dates range.")
                end if
                call wx_date_time_delete(first_valid)
                call wx_date_time_delete(last_valid)
            else
                call log_warning("Date range not supported.")
            end if

            call wx_date_time_delete(lo)
            call wx_date_time_delete(hi)
            call wx_date_time_delete(today)
            call wx_date_span_delete(diff)
        else
            if (wx_calendar_ctrl_base_set_date_range(g_cal, c_null_ptr, &
                    c_null_ptr)) then
                call log_status("Date choice is unlimited now.")
            else
                call log_warning("Date range not supported.")
            end if
        end if

        call wx_window_refresh(g_cal, .true.)
    end subroutine limit_date_range

    !--------------------------------------------------------------------------
    ! MyFrame::OnCalToggleResizable()
    !--------------------------------------------------------------------------
    subroutine toggle_resizable(on)
        logical, intent(in) :: on
        type(wxsizeritem_t) :: item

        item = wx_sizer_get_item_window(g_sizer, g_cal, .false.)
        if (item%is_valid()) then
            if (on) then
                call wx_sizer_item_set_proportion(item, 1_c_int)
                call wx_sizer_item_set_flag(item, wxEXPAND())
            else
                call wx_sizer_item_set_proportion(item, 0_c_int)
                call wx_sizer_item_set_flag(item, wxALIGN_CENTER())
            end if
        end if

        call wx_sizer_layout(g_sizer)
    end subroutine toggle_resizable

    !--------------------------------------------------------------------------
    ! MyFrame::OnCalRClick() -- bound on the calendar control itself
    !--------------------------------------------------------------------------
    subroutine on_cal_rclick(fun, data, evt) bind(C)
        type(c_ptr), value :: fun, data, evt
        type(wxmouseevent_t) :: mev
        type(wxdatetime_t) :: dt
        integer(c_int), target :: wd
        integer(c_int) :: x, y, hit
        character(len=64) :: buf
        character(len=:), allocatable :: msg

        if (.not. c_associated(evt)) return

        mev = wxmouseevent_from_ptr(evt, .false.)
        x = wx_mouse_event_get_x(mev)
        y = wx_mouse_event_get_y(mev)

        dt = wx_date_time_create()
        wd = 0_c_int
        hit = wx_calendar_ctrl_base_hit_test(g_cal, x, y, dt, wd)

        write (buf, '(a,i0,a,i0,a)') "Point (", int(x), ", ", int(y), ") is "

        if (hit == wxCAL_HITTEST_HEADER()) then
            msg = trim(buf) // "over " // weekday_name(int(wd))
        else if (hit == wxCAL_HITTEST_DAY()) then
            msg = trim(buf) // "over " // iso_date(dt)
        else if (hit == wxCAL_HITTEST_INCMONTH()) then
            msg = trim(buf) // "over next month button"
        else if (hit == wxCAL_HITTEST_DECMONTH()) then
            msg = trim(buf) // "over previous month button"
        else if (hit == wxCAL_HITTEST_SURROUNDING_WEEK()) then
            msg = trim(buf) // "over a day from another month"
        else
            ! wxCAL_HITTEST_NOWHERE (and the C++ wxFAIL_MSG default branch)
            msg = trim(buf) // "nowhere"
        end if

        call log_message(msg)
        call wx_date_time_delete(dt)
    end subroutine on_cal_rclick

end module calendar_ops


