    !--------------------------------------------------------------------------
    ! Calendar control events (MyPanel event table)
    !--------------------------------------------------------------------------
    subroutine on_calendar(fun, data, evt) bind(C)
        type(c_ptr), value :: fun, data, evt
        type(wxcalendarevent_t) :: cev
        type(wxdatetime_t) :: dt
        integer :: day, month, year
        logical :: mark
        character(len=2) :: un

        if (.not. c_associated(evt)) return

        cev = wxcalendarevent_from_ptr(evt, .false.)
        dt = wx_date_time_create()
        call wx_calendar_event_get_date(cev, dt%ptr)

        day = int(wx_date_time_get_day(dt, wxDateTime_Local()))
        month = int(wx_date_time_get_month(dt, wxDateTime_Local()))
        year = int(wx_date_time_get_year(dt, wxDateTime_Local()))

        ! mark = !s_dateLast.IsValid() || event.GetDate() != s_dateLast
        mark = (.not. g_last_valid) .or. (day /= g_last_day) .or. &
            (month /= g_last_month) .or. (year /= g_last_year)

        g_last_valid = .true.
        g_last_day = day
        g_last_month = month
        g_last_year = year

        if (mark) then
            un = ""
        else
            un = "un"
        end if

        call wx_calendar_ctrl_base_mark(g_cal, int(day, c_int), mark)

        call log_message("Selected (and " // trim(un) // "marked) " // &
            iso_date(dt) // " from calendar.")

        call wx_date_time_delete(dt)
    end subroutine on_calendar

