        type(wxFrame_t), intent(in) :: frame
        type(c_ptr), dimension(XPM_NO_LINES), target :: line_ptrs
        type(c_ptr) :: bitmap, icon
        integer :: i

        do i = 1, XPM_NO_LINES
            line_ptrs(i) = c_loc(xpm_lines(i)(1:1))
        end do

        bitmap = wxBitmap_CreateFromXPM(c_loc(line_ptrs))
        if (.not. c_associated(bitmap)) return
        if (wxBitmap_IsOk(bitmap) == 0) then
            call wxBitmap_Delete(bitmap)
            return
        end if

        icon = wxIcon_CreateDefault()
        if (c_associated(icon)) then
            call wxIcon_CopyFromBitmap(icon, bitmap)
            if (wxIcon_IsOk(icon) /= 0) call wxFrame_SetIcon(frame%ptr, icon)
            call wxIcon_Delete(icon)
        end if

        call wxBitmap_Delete(bitmap)
    end subroutine set_sample_icon

