module calendar_util
    use, intrinsic :: iso_c_binding
    use kwx_types
    use kwxffi, only: LogMessage, LogStatus, LogWarning
    use wx_string, only: to_wxstring, from_wxstring, wxString_Delete
    use wx_date_time
    use wx_menu_bar, only: wx_menu_bar_is_checked, wx_menu_bar_check
    use calendar_globals
    implicit none
    private

    public :: log_message, log_status, log_warning
    public :: iso_date, iso_time, month_name, weekday_name, make_datetime
    public :: menu_checked, menu_set_checked

contains

    !--------------------------------------------------------------------------
    ! Log helpers: wxLogMessage / wxLogStatus / wxLogWarning
    !--------------------------------------------------------------------------
    subroutine log_message(msg)
        character(len=*), intent(in) :: msg
        type(c_ptr) :: p
        p = to_wxstring(msg)
        call LogMessage(p)
        call wxString_Delete(p)
    end subroutine log_message

    subroutine log_status(msg)
        character(len=*), intent(in) :: msg
        type(c_ptr) :: p
        p = to_wxstring(msg)
        call LogStatus(p)
        call wxString_Delete(p)
    end subroutine log_status

    subroutine log_warning(msg)
        character(len=*), intent(in) :: msg
        type(c_ptr) :: p
        p = to_wxstring(msg)
        call LogWarning(p)
        call wxString_Delete(p)
    end subroutine log_warning

    !--------------------------------------------------------------------------
    ! wxDateTime helpers
    !--------------------------------------------------------------------------
    function iso_date(dt) result(s)
        type(wxdatetime_t), intent(in) :: dt
        character(len=:), allocatable :: s
        s = ""
        if (.not. c_associated(dt%ptr)) return
        if (.not. wx_date_time_is_valid(dt)) return
        s = wx_date_time_format_iso_date(dt)
    end function iso_date

    function iso_time(dt) result(s)
        type(wxdatetime_t), intent(in) :: dt
        character(len=:), allocatable :: s
        s = ""
        if (.not. c_associated(dt%ptr)) return
        if (.not. wx_date_time_is_valid(dt)) return
        s = wx_date_time_format_iso_time(dt)
    end function iso_time

    function month_name(month) result(s)
        integer, intent(in) :: month
        character(len=:), allocatable :: s
        ! wxDateTime::Name_Full == 0x01
        s = wx_date_time_get_month_name(int(month, c_int), 1_c_int)
    end function month_name

    function weekday_name(weekday) result(s)
        integer, intent(in) :: weekday
        character(len=:), allocatable :: s
        ! wxDateTime::Name_Full == 0x01
        s = wx_date_time_get_week_day_name(int(weekday, c_int), 1_c_int)
    end function weekday_name

    ! wxDateTime(day, month, year, hour, minute, second)
    function make_datetime(day, month, year, hour, minute, second) result(dt)
        integer, intent(in) :: day, month, year, hour, minute, second
        type(wxdatetime_t) :: dt
        dt = wx_date_time_create()
        call wx_date_time_set(dt, int(day, c_int), int(month, c_int), &
            int(year, c_int), int(hour, c_int), int(minute, c_int), &
            int(second, c_int), 0_c_int)
    end function make_datetime

    function menu_checked(id) result(checked)
        integer, intent(in) :: id
        logical :: checked
        checked = wx_menu_bar_is_checked(g_menu_bar, int(id, c_int))
    end function menu_checked

    subroutine menu_set_checked(id, checked)
        integer, intent(in) :: id
        logical, intent(in) :: checked
        call wx_menu_bar_check(g_menu_bar, int(id, c_int), checked)
    end subroutine menu_set_checked

end module calendar_util


