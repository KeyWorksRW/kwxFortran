        res = wx_dialog_show_modal(dlg)

        if (res == wxID_OK()) then
            dt_out = wx_date_time_create()
            call wx_time_picker_ctrl_get_value(picker, dt_out)
            accepted = .true.
        end if

        ok = wx_window_destroy(dlg)
        g_time_text%ptr = c_null_ptr
        g_time_text%owned = .false.
    end subroutine run_time_dialog

    subroutine on_time_change(fun, data, evt) bind(C)
        type(c_ptr), value :: fun, data, evt
        type(wxdateevent_t) :: dev
        type(wxdatetime_t) :: dt
        if (.not. c_associated(evt)) return

        dev = wxdateevent_from_ptr(evt, .false.)
        dt = wx_date_time_create()
        call wx_date_event_get_date(dev, dt)
        call wx_window_set_label(g_time_text, iso_time(dt))
        call wx_date_time_delete(dt)
    end subroutine on_time_change

    !--------------------------------------------------------------------------
    ! wxMessageBox helper
    !--------------------------------------------------------------------------
    function message_box(msg, caption) result(res)
        character(len=*), intent(in) :: msg, caption
        integer(c_int) :: res
        type(c_ptr) :: mp, cp
        mp = to_wxstring(msg)
        cp = to_wxstring(caption)
        ! wxMessageBox(msg, caption) in OnAskDate has no explicit parent.
        res = kwxMessageBox(mp, cp, wxOK(), c_null_ptr, -1_c_int, -1_c_int)
        call wxString_Delete(mp)
        call wxString_Delete(cp)
    end function message_box

end module calendar_handlers


