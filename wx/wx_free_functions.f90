        class(wxwindow_t), intent(in) :: parent
        type(c_ptr) :: what_ptr
        type(c_ptr) :: extension_ptr
        type(c_ptr) :: default_name_ptr
        type(c_ptr) :: result_text_ptr
        character(len=:), allocatable :: result_text
        what_ptr = to_wxstring(what)
        extension_ptr = to_wxstring(extension)
        default_name_ptr = to_wxstring(default_name)
        result_text_ptr = wxSaveFileSelector(what_ptr, extension_ptr, default_name_ptr, parent%ptr)
        result_text = from_wxstring(result_text_ptr)
        call wxString_Delete(result_text_ptr)
        call wxString_Delete(what_ptr)
        call wxString_Delete(extension_ptr)
        call wxString_Delete(default_name_ptr)
    end function wx_save_file_selector

