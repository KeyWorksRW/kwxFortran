        help_ptr = to_wxstring(help)
        call wxMenu_PrependRadioItem(self%ptr, id, text_ptr, help_ptr)
        call wxString_Delete(text_ptr)
        call wxString_Delete(help_ptr)
    end subroutine wx_menu_prepend_radio_item

