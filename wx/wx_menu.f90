        call wxString_Delete(help_ptr)
    end subroutine wx_menu_prepend_check_item

    subroutine wx_menu_prepend_radio_item(self, id, text, help)
        class(wxmenu_t), intent(in) :: self
        integer(c_int), intent(in) :: id
        character(len=*), intent(in) :: text
        character(len=*), intent(in) :: help
        type(c_ptr) :: text_ptr
        type(c_ptr) :: help_ptr
